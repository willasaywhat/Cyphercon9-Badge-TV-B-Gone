LCDcs      = machine.Pin(7,  machine.Pin.OUT, value=1)
LCDreset   = machine.Pin(8,  machine.Pin.OUT, value=0)
LCDdataCMD = machine.Pin(9,  machine.Pin.OUT, value=0)
LCDsck     = machine.Pin(10, machine.Pin.ALT, value=0)
LCDmosi    = machine.Pin(11, machine.Pin.ALT, value=0)
LCDmiso    = machine.Pin(12, machine.Pin.OUT, value=0)

SPI1 = machine.SPI(
    1,
    baudrate=5000000,
    polarity=1,
    phase=1,
    bits=8,
    firstbit=machine.SPI.MSB,
    sck=LCDsck,
    mosi=LCDmosi,
    miso=LCDmiso)

screen_buffer = bytearray(528)  # 4 pages * 132 columns
_sbuf = memoryview(screen_buffer)  # zero-copy view for bulk SPI writes

def spiByte(data, DC):
    xfer = bytearray(1)
    xfer[0] = data & 0xFF
    LCDdataCMD.value(DC)
    LCDcs.off()
    SPI1.write(xfer)
    LCDcs.on()

def spi2Byte(data, data1, DC):
    xfer = bytearray(2)
    xfer[0] = data & 0xFF
    xfer[1] = data1 & 0xFF
    LCDdataCMD.value(DC)
    LCDcs.off()
    SPI1.write(xfer)
    LCDcs.on()

def initLCD():
    utime.sleep(0.1)
    LCDreset.value(0)
    utime.sleep(0.1)
    LCDreset.value(1)
    utime.sleep(0.1)
    spiByte(0xE2, 0)
    utime.sleep(0.1)
    spi2Byte(0xF8, 0x01, 0)
    spiByte(0x23, 0)
    spiByte(0x2C, 0)
    spiByte(0x2E, 0)
    spiByte(0x2F, 0)
    spiByte(0xA2, 0)
    spiByte(0xA1, 0)
    spiByte(0xC8, 8)
    spi2Byte(0x81, 0x12, 0)
    spiByte(0x40, 0)
    spiByte(0xA6, 0)
    spiByte(0xAF, 0)
    spiByte(0x00, 0)
    spiByte(0x10, 0)
    spiByte(0xB0, 0)
    spiByte(0xAF, 0)
    clearLCD()

def clearLCD():
    setRowColLCD(0, 0)
    for j in range(4):
        spi2Byte(0x10, 0x00, 0)
        spiByte(0xB0 + j, 0)
        for i in range(0x84):
            spiByte(0x00, 1)
    setRowColLCD(0, 0)

def setRowColLCD(row, col):
    spi2Byte((((col >> 4) & 0x0F) | 0x10), (col & 0x0F), 0)
    spiByte(((row & 0x0F) | 0xB0), 0)

def pset(x, y, value):
    if 0 <= x <= 131 and 0 <= y <= 31:
        by = y >> 3
        ry = y & 7
        idx = (by * 132) + x
        mask = ~(1 << ry) & 0xFF
        temp = screen_buffer[idx] & mask
        if value:
            temp |= (1 << ry)
        screen_buffer[idx] = temp

def flip():
    # Write each page as one bulk SPI transfer instead of 132 individual bytes.
    for page in range(4):
        setRowColLCD(page, 0)
        LCDdataCMD.value(1)
        LCDcs.off()
        SPI1.write(_sbuf[page * 132:(page + 1) * 132])
        LCDcs.on()

def lcd_display_off():
    """Turn off the LCD panel to save power (ST7565 display-off command)."""
    spiByte(0xAE, 0)

def lcd_display_on():
    """Turn the LCD panel back on (ST7565 display-on command)."""
    spiByte(0xAF, 0)

def top_blit(character_index, tile_index):
    if not (0 <= character_index <= 255 and 0 <= tile_index <= 15):
        return
    character_origin = character_index * 16
    column_offset = tile_index * 8
    for column in range(8):
        l = tymkrscii_map[character_origin + (column * 2)]
        u = tymkrscii_map[character_origin + (column * 2) + 1]
        for y in range(8):
            pset(column + column_offset, y + 7, l & 1)
            l >>= 1
        for y in range(5):
            pset(column + column_offset, y + 15, u & 1)
            u >>= 1

def bottom_blit(character_index, tile_index):
    if not (0 <= character_index <= 255 and 0 <= tile_index <= 15):
        return
    character_origin = character_index * 16
    column_offset = tile_index * 8
    for column in range(8):
        l = tymkrscii_map[character_origin + (column * 2)]
        u = tymkrscii_map[character_origin + (column * 2) + 1]
        for y in range(8):
            pset(column + column_offset, y + 20, l & 1)
            l >>= 1
        for y in range(4):
            pset(column + column_offset, y + 28, u & 1)
            u >>= 1

def set_top_text(text):
    t = (text + "                ")[:16]
    for x in range(16):
        top_blit(ord(t[x]), x)

def set_bottom_text(text):
    t = (text + "                ")[:16]
    for x in range(16):
        bottom_blit(ord(t[x]), x)

