def ir_mark(us):
    """Transmit 38 kHz carrier burst for `us` microseconds."""
    ir_pwm.duty_u16(32768)
    utime.sleep_us(us)

def ir_space(us):
    """Silence (no carrier) for `us` microseconds."""
    ir_pwm.duty_u16(0)
    utime.sleep_us(us)

def send_code(code):
    """Send one IR code. Format: (name, on_us, off_us, on_us, ...)"""
    pulses = code[1:]
    for i, duration in enumerate(pulses):
        if i % 2 == 0:
            ir_mark(duration)
        else:
            ir_space(duration)
    ir_pwm.duty_u16(0)

_DISPLAY_EVERY = 1  # refresh LCD on every code

def send_all_codes():
    """Send all CODES in sequence. Returns True=done, False=cancelled."""
    total = len(CODES)
    for i, code in enumerate(CODES):
        if cancel.value() == 0:  # active LOW
            show_status(
                "CANCELLED!      ",
                "AT " + ("000" + str(i))[-3:] + "/" + ("000" + str(total))[-3:] + "       ",
                i, total
            )
            print("Cancelled at", code[0], str(i) + "/" + str(total))
            return False

        if i == 0 or i % _DISPLAY_EVERY == 0:
            num_str = ("000" + str(i + 1))[-3:] + "/" + ("000" + str(total))[-3:]
            show_status(
                "SENDING " + num_str + "   ",
                "CODE: " + code[0] + "         ",
                i + 1, total
            )
        print("Sending", code[0], str(i + 1) + "/" + str(total))
        led.toggle()
        send_code(code)
        gc.collect()

    ir_pwm.duty_u16(0)
    led.value(0)
    return True

